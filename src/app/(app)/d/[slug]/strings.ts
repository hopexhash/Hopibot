/** Plain-data strings for client components (functions are resolved on the server first). */
export type ClientStrings = Omit<Strings, "vat"> & { vatLabel: string };
export function clientStrings(s: Strings, vatPct: number): ClientStrings {
  const { vat, ...rest } = s;
  return { ...rest, vatLabel: vat(vatPct) };
}
